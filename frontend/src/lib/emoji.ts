export const DEFAULT_EMOJI = '📌';

function match(text: string): string | undefined {
  const t = text.toLowerCase();
  return RULES.find(([, words]) => words.some((w) => t.includes(w)))?.[0];
}

export function emojiFor(title: string, description?: string | null): string {
  return match(title) ?? (description ? match(description) : undefined) ?? DEFAULT_EMOJI;
}
